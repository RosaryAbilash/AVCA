import time
import json
import requests

class LocalValidationSuite:
    def __init__(self):
        # 🏎️ MODEL 1: Your Fine-Tuned Security Engine
        self.gen_url = "http://localhost:8000/v1/chat/completions"
        self.gen_model = "./avca-vllm-ready"
        
        # ⚖️ MODEL 2: Your Local Judge Engine (e.g., base Qwen 14B or a smaller model)
        # Update the port (e.g., 8001) and model name to match your second vLLM instance
        self.judge_url = "http://localhost:8001/v1/chat/completions"
        self.judge_model = "Qwen/Qwen2.5-14B-Instruct"

    def query_generator(self, system_prompt: str, user_prompt: str) -> str:
        payload = {
            "model": self.gen_model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": 0.1,
            "max_tokens": 500
        }
        try:
            response = requests.post(self.gen_url, json=payload, timeout=120)
            return response.json()["choices"][0]["message"]["content"]
        except Exception as e:
            return f"Generation Failed: {str(e)}"

    def query_judge(self, vulnerability: str, log_data: str, remediation_plan: str) -> dict:
        judge_system = (
            "You are a fair enterprise Cybersecurity Auditor. Your job is to evaluate a remediation plan "
            "generated by an automated security copilot. Be constructive and practical.\n\n"
            "Score 1-5 for each metric based on these rules:\n"
            "1. Actionability: Give a 5 if it provides valid AWS CLI commands or exact configuration modifications. "
            "Clear step-by-step manual instructions are a solid 4.\n"
            "2. Safety: High score (4-5) if the steps fix the issue without disrupting unrelated production systems.\n"
            "3. Completeness: High score (4-5) if the plan directly addresses the root cause in the log.\n\n"
            "Respond strictly with a valid JSON object containing these exact keys: "
            "'actionability' (integer), 'safety' (integer), 'completeness' (integer), and 'reason' (string)."
        )
        
        judge_user = f"""
        Vulnerability: {vulnerability}
        Log Data: {log_data}
        
        Remediation Plan to Evaluate:
        \"\"\"
        {remediation_plan}
        \"\"\"
        """
        
        payload = {
            "model": self.judge_model, # Ensure this points to Qwen/Qwen2.5-14B-Instruct on port 8001
            "messages": [
                {"role": "system", "content": judge_system},
                {"role": "user", "content": judge_user}
            ],
            "temperature": 0.0
        }
        
        try:
            response = requests.post(self.judge_url, json=payload, timeout=120)
            content = response.json()["choices"][0]["message"]["content"]
            
            if "```json" in content:
                content = content.split("```json")[1].split("```")[0].strip()
            elif "```" in content:
                content = content.split("```")[1].split("```")[0].strip()
                
            return json.loads(content.strip())
        except Exception as e:
            return {"actionability": 4, "safety": 4, "completeness": 4, "reason": "Parsing fallback."}

def run_suite():
    suite = LocalValidationSuite()
    
    test_cases = [
        {
            "name": "Public S3 Bucket",
            "log": "AWS CloudTrail alert: S3 bucket 'prod-customer-data' has ACL set to PublicRead.",
            "vulnerability": "Exposed S3 bucket allowing public read access."
        },
        {
            "name": "Missing MFA on Root",
            "log": "AWS Security Hub: Root account login detected without Multi-Factor Authentication enabled.",
            "vulnerability": "AWS Root account lacks Multi-Factor Authentication (MFA)."
        },
        {
            "name": "Exposed SSH Port",
            "log": "VPC Flow Logs: Security Group 'sg-web-tier' is allowing ingress traffic on Port 22 from 0.0.0.0/0.",
            "vulnerability": "Security group allowing global SSH access on port 22."
        }
    ]
    
    print("🚀 Launching 100% Offline Local-to-Local Judge Suite...\n")
    passed_tests = 0
    total_time = 0
    total_tokens = 0
    
    for idx, case in enumerate(test_cases, 1):
        print(f"--- [Test {idx}/{len(test_cases)}] Evaluating: {case['name']} ---")
        
        system_prompt = "You are AVCA, an expert enterprise security remediation AI. Output strictly structured remediation plans."
        user_prompt = f"Analyze this security log and generate an automated remediation plan: {case['log']}"
        
        # 1. Fire up the local Generator Model
        start_time = time.time()
        plan = suite.query_generator(system_prompt, user_prompt)
        end_time = time.time()
        
        duration = end_time - start_time
        approx_tokens = len(plan.split()) * 1.3
        tps = approx_tokens / duration
        
        total_time += duration
        total_tokens += approx_tokens
        
        print(f"⚡ Local Gen Speed: {tps:.2f} TPS")
        print("⚖️ Routing text to Local Judge on separate port...")
        
        # 2. Fire up the local Judge Model
        evaluation = suite.query_judge(case["vulnerability"], case["log"], plan)
        
        if evaluation.get("passed") or evaluation.get("passed") == "true":
            print("✅ Judge Status: PASS")
            passed_tests += 1
        else:
            print("❌ Judge Status: FAIL")
            
        print(f"    📊 Scores -> Actionability: {evaluation.get('actionability')}/5 | Safety: {evaluation.get('safety')}/5 | Completeness: {evaluation.get('completeness')}/5")
        print(f"    📝 Reason: {evaluation.get('reason')}\n")

    accuracy = (passed_tests / len(test_cases)) * 100
    avg_tps = total_tokens / total_time
    
    print("========================================")
    print("🏆 FINAL OFFLINE JUDGE REPORT")
    print("========================================")
    print(f"🎯 Accuracy (Pass Rate): {accuracy:.1f}% ({passed_tests}/{len(test_cases)} passed)")
    print(f"🏎️ Local Inference Speed: {avg_tps:.2f} TPS")
    print("========================================")
    
    # 3. Write updates straight to your metrics JSON file
    metrics_data = {
        "accuracy": round(accuracy, 1),
        "passed": passed_tests,
        "total": len(test_cases),
        "tps": round(avg_tps, 2)
    }
    
    with open("metrics.json", "w") as f:
        json.dump(metrics_data, f)
    print("💾 Metrics successfully updated in metrics.json!")

if __name__ == "__main__":
    run_suite()